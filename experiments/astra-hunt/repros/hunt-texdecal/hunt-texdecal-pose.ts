import * as THREE from 'three';
import { createBuilder } from '../../../../src/builder';
const tex = new THREE.DataTexture(new Uint8Array([255,255,255,255]), 1, 1);
const b = createBuilder({name:'poseDecal'});
const root = b.joint('root',{at:[0,0,0], dir:[0,1,0]});
const chain = b.chain('arm', [[0,0,0],[0,1,0],[0,2,0]], {parent:root, names:['arm0','arm1','arm2']});
const tube = b.sweep(chain, .22, {segments:8, color:'#888888'});
const surface = b.surface(tube);
const hit = tube.at(.5, 0);
const decal = b.decal(tube, tex, {at:hit, dir:hit.n, size:[.1,.1], segments:[3,3]});
b.root.updateMatrixWorld(true);
const beforeVerts=(()=>{const p=decal.mesh.geometry.getAttribute('position'); return Array.from({length:p.count},(_,i)=>new THREE.Vector3().fromBufferAttribute(p,i).applyMatrix4(decal.mesh.matrixWorld));})();
const beforeErrors=beforeVerts.map(v=>v.distanceTo(surface.nearest(v).at));
const before = new THREE.Box3().setFromObject(decal.mesh,true);
b.pose('arm1',{axis:[0,0,1],deg:35});
b.root.updateMatrixWorld(true);
const after = new THREE.Box3().setFromObject(decal.mesh,true);
const p=decal.mesh.geometry.getAttribute('position'); const verts=Array.from({length:p.count},(_,i)=>new THREE.Vector3().fromBufferAttribute(p,i).applyMatrix4(decal.mesh.matrixWorld));
const errors=verts.map(v=>v.distanceTo(surface.nearest(v).at));
console.log('posed-skinned-decal',{before:before.min.toArray().map(x=>+x.toFixed(4)),after:after.min.toArray().map(x=>+x.toFixed(4)),beforeMaxDistance:Math.max(...beforeErrors),afterMaxDistance:Math.max(...errors),beforeMinDistance:Math.min(...beforeErrors),afterMinDistance:Math.min(...errors),vertexCount:p.count,skinBones:decal.mesh.userData.skinBones});
