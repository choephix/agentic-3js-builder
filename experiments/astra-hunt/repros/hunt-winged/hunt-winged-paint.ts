import * as THREE from "three";
import { createBuilder } from "../../../../src/builder";
import { paint } from "../../../../src/paint";
const shared = paint((p, n, s) => n.y > 0 ? (s[1] < 0.5 ? "#e88" : "#b44") : p.y > 1 ? "#844" : "#422");
const b = createBuilder({ name: "paint-wing", paintSize: 512 });
const root = b.joint("root", { at: [0, 1, 0] });
const body = b.chain("body", [[0, 1, 0], [0, 1, 0.5]], { parent: root, names: ["bodySpan", "bodyTip"], role: "spine" });
b.sweep(body, 0.2, { color: shared, name: "body" });
const a = b.chain("edgeA", [[0.2, 1, 0], [0.8, 1.1, -0.3]], { parent: root, names: ["edgeABase", "edgeATip"], role: "digit" });
const c = b.chain("edgeB", [[0.2, 1, 0], [0.75, 0.8, -0.28]], { parent: root, names: ["edgeBBase", "edgeBTip"], role: "digit" });
const [membrane] = b.membrane(a, c, { thickness: 0.01, color: shared, rows: 2, cols: 5, name: "membrane" });
const scene = b.root;
const meshes: THREE.Mesh[] = [];
scene.traverse((object) => { if ((object as THREE.Mesh).isMesh) meshes.push(object as THREE.Mesh); });
const bodyMesh = meshes.find((mesh) => mesh.name === "body");
if (!bodyMesh) throw new Error("body missing");
const bodyMaterial = bodyMesh.material as THREE.MeshStandardMaterial;
const membraneMaterial = membrane.material as THREE.MeshStandardMaterial;
console.log({ bodyPaintMap: bodyMaterial.map?.name, membranePaintMap: membraneMaterial.map?.name, sameMap: bodyMaterial.map === membraneMaterial.map, bodyUv: !!bodyMesh.geometry.getAttribute("uv"), membraneUv: !!membrane.geometry.getAttribute("uv"), finite: meshes.every((mesh) => Array.from(mesh.geometry.getAttribute("position").array).every(Number.isFinite)) });
